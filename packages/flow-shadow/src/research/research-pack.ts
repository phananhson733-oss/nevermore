import type {
  BriefOutlineProjectionStats,
  ContentShadowInputManifest,
  ResearchPack,
  ResearchSource,
} from "../types.ts";

/**
 * Deterministic research-pack assembly (Slice 2 Task 4).
 *
 * The pack is a pure projection of the frozen input manifest: same manifest in,
 * byte-identical pack out. It performs no retrieval — external authority
 * research and its A/B/C/D grading are Task 6 — so every source it emits is a
 * first-party project record the customer already confirmed, and the gaps
 * are stated as explicit limitations instead of being filled with invented
 * evidence.
 */

/**
 * The fixed drafting scaffold. Determinism lives in the scaffold and the later
 * verification pass, never in generation (the ported Flow tooling works the
 * same way: it writes the prompt and gates the result, it does not invent the
 * body).
 */
export const CONTENT_SHADOW_OUTLINE: readonly string[] = [
  "Title",
  "Summary",
  "Problem",
  "Approach",
  "Evidence",
  "FAQ",
  "Sources",
  "Call To Action",
];

const NO_EXTERNAL_RESEARCH_LIMITATION =
  "This pack carries only first-party frozen project records; no external source was retrieved or graded.";
const NO_METRIC_LIMITATION =
  "No search demand or generative citation metric was read for this run; identities are frozen without metrics.";
/**
 * What the QA gate does NOT check, stated as a limitation of the judgement
 * rather than as its absence.
 *
 * This slot used to read "SEO/GEO red-line, structure and citability judgement
 * is not implemented yet" and was emitted unconditionally, including on runs
 * the gate had really judged and `blocked`. The API returns this list verbatim,
 * so a reviewer looking at a blocked draft was told in the same response that
 * the block was a placeholder — which cancels out the one verdict that matters.
 * The gate is implemented (Task 6); these are its real, remaining gaps.
 */
const QA_SCOPE_LIMITATION =
  "The SEO/GEO red-line, structure and citability judgement is deterministic and runs over frozen inputs only. It performs NO plagiarism detection (the run contains no SERP corpus), NO external fact-checking, and NO brand-tone review; and because this pack retrieves nothing external, it can report that a reference is unverifiable here but never that it is false.";

const BRIEF_SOURCE_LIMITATION =
  "The confirmed content brief revision is never regenerated by the shadow pipeline; its section headings, frozen cluster keywords and page-assignment decision are extracted into the draft prompt as a coverage checklist, while its prose body never enters the prompt.";

/**
 * The two first-party identity sources.
 *
 * Their limitation is the load-bearing half: a first-party URL proves that a
 * link points at the customer's own property, and nothing more. It is not
 * evidence for any assertion the draft makes, so the QA gate must never let one
 * satisfy a research attribution — which is why these are excluded from the
 * external-citable count the citation rules read.
 */
const SITE_ORIGIN_SOURCE_LIMITATION =
  "First-party identity only: this is the project's own site origin, frozen at accept time. It proves a link points at the customer's own property; it is NOT evidence for any claim the draft makes, and no page under it was fetched or verified for this run.";
const CONVERSION_SOURCE_LIMITATION =
  "First-party identity only: the primary conversion target the frozen ICP profile carries. It proves a call to action points at the customer's own conversion destination; it is NOT evidence for any claim, and the destination was not fetched or verified for this run.";

/**
 * Loud degradation (decision O-4). Extraction failure means the brief -> draft
 * causal chain is broken for this run, which is exactly the defect Task 4b
 * exists to fix. It is stated here, it forces the QA verdict off `passed`, and
 * this list is what the read API surfaces as `research.limitations`.
 */
const BRIEF_OUTLINE_UNAVAILABLE_LIMITATION =
  "Content brief outline extraction FAILED: the pinned brief revision carried no machine-readable `## ` section heading, so this draft was NOT guided by the brief. Review the draft against the brief by hand.";
const SEARCH_SOURCE_LIMITATION =
  "Search observation identity only; carries no demand volume for this run.";
const GENERATIVE_SOURCE_LIMITATION =
  "Generative observation identity only; carries no answer-sample metric for this run.";
const COMPETITOR_SOURCE_LIMITATION =
  "Competitor identity only; no competitor page was fetched or analysed for this run.";

function briefSource(manifest: ContentShadowInputManifest): ResearchSource {
  return {
    kind: "content_brief",
    ref: manifest.contentBriefArtifactId,
    authorityTier: "A",
    limitation: BRIEF_SOURCE_LIMITATION,
  };
}

/**
 * The customer's own web identity, in a fixed order. The conversion target is
 * omitted entirely when the frozen ICP carried none: an absent identity is
 * absent, never a placeholder a draft could resolve against.
 */
function firstPartySources(
  manifest: ContentShadowInputManifest,
): readonly ResearchSource[] {
  const conversionUrl = manifest.firstParty.icpPrimaryConversionUrl;
  return [
    {
      kind: "first_party_site",
      ref: manifest.firstParty.siteOrigin,
      authorityTier: "A",
      limitation: SITE_ORIGIN_SOURCE_LIMITATION,
    },
    ...(conversionUrl === null
      ? []
      : [
          {
            kind: "first_party_conversion" as const,
            ref: conversionUrl,
            authorityTier: "A" as const,
            limitation: CONVERSION_SOURCE_LIMITATION,
          },
        ]),
  ];
}

/**
 * Sources are emitted in a stable order (brief, then first-party identity, then
 * search, then generative, then competitors) over already-sorted identity sets,
 * so the pack is stable across processes and replays.
 */
function buildSources(
  manifest: ContentShadowInputManifest,
): readonly ResearchSource[] {
  return [
    briefSource(manifest),
    ...firstPartySources(manifest),
    ...manifest.searchCluster.keywordEntityIds.map(
      (ref): ResearchSource => ({
        kind: "search_query",
        ref,
        authorityTier: "A",
        limitation: SEARCH_SOURCE_LIMITATION,
      }),
    ),
    ...manifest.generativeQueryEntityIds.map(
      (ref): ResearchSource => ({
        kind: "generative_query",
        ref,
        authorityTier: "A",
        limitation: GENERATIVE_SOURCE_LIMITATION,
      }),
    ),
    ...manifest.competitorEntityIds.map(
      (ref): ResearchSource => ({
        kind: "competitor",
        ref,
        authorityTier: "A",
        limitation: COMPETITOR_SOURCE_LIMITATION,
      }),
    ),
  ];
}

/**
 * Limitations derived from the brief-outline projection, in a fixed order so
 * the pack stays byte-stable.
 */
function briefOutlineLimitations(
  manifest: ContentShadowInputManifest,
  stats: BriefOutlineProjectionStats,
): readonly string[] {
  const limitations: string[] = [];
  if (manifest.contentBriefOutline.briefSections.length === 0) {
    limitations.push(BRIEF_OUTLINE_UNAVAILABLE_LIMITATION);
  }
  // A PARTIAL extraction failure: the topics past the cap broke the same
  // brief -> draft causal chain, only for part of the brief. Decision O-4 spells
  // out total failure; its principle ("an honest shortfall beats a silent pass")
  // is what forbids leaving this one unsaid.
  if (stats.projectedSectionCount < stats.briefSectionCount) {
    limitations.push(
      `The pinned content brief carried ${stats.briefSectionCount} distinct section headings; only the first ${stats.projectedSectionCount} (in document order) reached the draft prompt, so ${stats.briefSectionCount - stats.projectedSectionCount} committed topic(s) did not guide this draft.`,
    );
  }
  if (stats.projectedKeywordCount < stats.clusterKeywordCount) {
    limitations.push(
      `The frozen search cluster holds ${stats.clusterKeywordCount} keywords; only the first ${stats.projectedKeywordCount} (ordered by normalized keyword) were projected into the brief outline.`,
    );
  }
  if (stats.unconfirmedMappingCount > 0) {
    limitations.push(
      `${stats.unconfirmedMappingCount} of ${stats.clusterKeywordCount} frozen cluster keywords carry an unconfirmed page-mapping review state; the outline's pageAssignment therefore reflects decisions no operator has confirmed.`,
    );
  }
  return limitations;
}

/** Project one frozen manifest into its deterministic research pack. */
export function buildResearchPack(
  manifest: ContentShadowInputManifest,
  briefOutlineStats: BriefOutlineProjectionStats,
): ResearchPack {
  return {
    adapterVersion: manifest.flowAdapterVersion,
    projectionVersion: manifest.projectionVersion,
    outputLocale: manifest.outputLocale,
    brief: {
      artifactId: manifest.contentBriefArtifactId,
      revision: manifest.contentBriefRevision,
    },
    outline: [...CONTENT_SHADOW_OUTLINE],
    briefOutline: {
      briefSections: [...manifest.contentBriefOutline.briefSections],
      targetKeywords: [...manifest.contentBriefOutline.targetKeywords],
      pageAssignment: manifest.contentBriefOutline.pageAssignment,
    },
    // Two independent shapes: never a shared volume (invariant 8).
    searchObservation: {
      clusterKey: manifest.searchCluster.clusterKey,
      keywordEntityIds: [...manifest.searchCluster.keywordEntityIds],
    },
    generativeObservation: {
      generativeQueryEntityIds: [...manifest.generativeQueryEntityIds],
    },
    competitorEntityIds: [...manifest.competitorEntityIds],
    sources: buildSources(manifest),
    limitations: [
      NO_EXTERNAL_RESEARCH_LIMITATION,
      NO_METRIC_LIMITATION,
      QA_SCOPE_LIMITATION,
      ...briefOutlineLimitations(manifest, briefOutlineStats),
    ],
  };
}

/** The pack as a plain JSON object for the `pack` jsonb column. */
export function researchPackToJson(
  pack: ResearchPack,
): Record<string, unknown> {
  return JSON.parse(JSON.stringify(pack)) as Record<string, unknown>;
}
