function compareText(left: string, right: string): number {
  if (left < right) return -1;
  if (left > right) return 1;
  return 0;
}

function sortedUnique(values: readonly string[]): readonly string[] {
  return [...new Set(values.map((value) => value.trim()).filter(Boolean))].sort(
    compareText,
  );
}

function truncate(value: string, limit: number): string {
  return value.length <= limit ? value : value.slice(0, limit);
}

function nullableTrimmed(value: string | null): string | null {
  if (value === null) return null;
  const trimmed = value.trim();
  return trimmed.length === 0 ? null : trimmed;
}

/**
 * Adapter limitations are audit output, not prose for this projection to
 * normalize. Preserve them byte-for-byte and append only limitations introduced
 * by pack assembly, in a fixed causal order.
 */
function appendPackLimitations(
  adapterLimitation: string | null,
  ...packLimitations: readonly (string | null)[]
): string | null {
  const additions = packLimitations.filter(
    (limitation): limitation is string => limitation !== null,
  );
  if (additions.length === 0) return adapterLimitation;
  const appended = additions.join(" ");
  return adapterLimitation === null
    ? appended
    : `${adapterLimitation} ${appended}`;
}

function cloneMetrics(
  metrics: ResearchSourceMetrics | null,
): ResearchSourceMetrics | null {
  if (metrics === null) return null;
  return {
    status: metrics.status,
    contentType: nullableTrimmed(metrics.contentType),
    bodyBytes: metrics.bodyBytes,
    wordCount: metrics.wordCount,
    responseMs: metrics.responseMs,
    redirectChain: metrics.redirectChain
      .slice(0, MAX_RESEARCH_SOURCE_REDIRECTS)
      .map((url) => url.trim()),
  };
}

