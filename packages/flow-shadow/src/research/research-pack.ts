function keywordSources(
  facts: readonly ContentShadowKeywordFact[],
  kind: "search_query" | "generative_query",
): readonly ResearchSource[] {
  return facts.map((fact) =>
    emptySource({
      kind,
      ref: fact.id,
      authorityTier: "A",
      label: fact.display,
      url: null,
      availability: "available",
      capturedAt: fact.lastSeen,
      evidenceRefs: fact.evidenceRefs,
      limitation:
        fact.evidenceRefs.length === 0
          ? kind === "search_query"
            ? SEARCH_SOURCE_WITHOUT_EVIDENCE_LIMITATION
            : GENERATIVE_SOURCE_WITHOUT_EVIDENCE_LIMITATION
          : kind === "search_query"
            ? SEARCH_SOURCE_LIMITATION
            : GENERATIVE_SOURCE_LIMITATION,
    }),
  );
}

function competitorSources(
  facts: readonly ContentShadowCompetitorFact[],
): readonly ResearchSource[] {
  return facts.map((fact) =>
    emptySource({
      kind: "competitor",
      ref: fact.id,
      authorityTier: "A",
      label: fact.name ?? fact.domain,
      // Identity alone must not turn an unfetched domain into citable evidence.
      url: null,
      availability: "available",
      limitation: COMPETITOR_SOURCE_LIMITATION,
    }),
  );
}

interface BoundedPageSource {
  readonly source: ResearchSource;
  readonly consumedCharacters: number;
  readonly bodyTruncated: boolean;
}

function boundedPageSource(
  snapshot: RetrievedResearchSnapshot,
  fields: {
    readonly label: string;
    readonly authorityTier: ResearchSource["authorityTier"];
    readonly evidenceRefs: readonly string[];
  },
  remainingCharacters: number,
): BoundedPageSource {
  const originalText = snapshot.contentText;
  const sourceCap = Math.min(
    MAX_RESEARCH_SOURCE_CONTENT_CHARS,
    Math.max(0, remainingCharacters),
  );
  const boundedText =
    originalText === null ? null : truncate(originalText, sourceCap);
  const packContentTruncated =
    originalText !== null &&
    (boundedText?.length ?? 0) < originalText.length;
  const boundedExcerpt =
    snapshot.excerpt === null
      ? null
      : truncate(snapshot.excerpt, MAX_RESEARCH_SOURCE_EXCERPT_CHARS);
  const packExcerptTruncated =
    snapshot.excerpt !== null &&
    (boundedExcerpt?.length ?? 0) < snapshot.excerpt.length;
  const missingAvailableBody =
    snapshot.availability === "available" && originalText === null;
  const inferredAvailabilityLimitation =
    snapshot.limitation !== null
      ? null
      : snapshot.availability === "partial"
        ? "Retrieval returned only a partial page."
        : snapshot.availability === "unavailable"
          ? "Retrieval did not return an available page."
          : missingAvailableBody
            ? "Retrieval marked the page available but supplied no content body."
            : null;
  const packContentLimitation = packContentTruncated
    ? `Content text exceeded the bounded research-pack limit and was truncated to ${boundedText?.length ?? 0} characters; contentHash still identifies the complete retrieved text.`
    : null;
  const packExcerptLimitation = packExcerptTruncated
    ? `Excerpt exceeded the bounded research-pack limit and was truncated to ${MAX_RESEARCH_SOURCE_EXCERPT_CHARS} characters.`
    : null;
  const projectedAvailability =
    packContentTruncated && snapshot.availability === "available"
      ? "partial"
      : snapshot.availability;
  const evidenceRefs = sortedUnique([
    ...fields.evidenceRefs,
    ...snapshot.evidenceRefs,
  ]);
  if (evidenceRefs.length > MAX_RESEARCH_SOURCE_EVIDENCE_REFS) {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} has too many merged evidence references`,
    );
  }
  return {
    source: {
      kind: snapshot.kind,
      ref: snapshot.ref,
      authorityTier: fields.authorityTier,
      label: fields.label,
      url: snapshot.url,
      // Adapter availability remains authoritative unless this projection
      // itself removes body content. A bounded preview alone does not make the
      // retained body partial.
      availability: projectedAvailability,
      capturedAt: snapshot.capturedAt,
      urlHash: snapshot.urlHash,
      contentHash: snapshot.contentHash,
      contentHashMethod: snapshot.contentHashMethod,
      contentText: boundedText,
      contentTruncated:
        snapshot.contentTruncated || packContentTruncated,
      excerpt: boundedExcerpt,
      excerptTruncated:
        snapshot.excerptTruncated || packExcerptTruncated,
      metrics: cloneMetrics(snapshot.metrics),
      evidenceRefs,
      limitation: appendPackLimitations(
        snapshot.limitation,
        inferredAvailabilityLimitation,
        packContentLimitation,
        packExcerptLimitation,
      ),
    },
    consumedCharacters: boundedText?.length ?? 0,
    bodyTruncated:
      snapshot.contentTruncated || packContentTruncated,
  };
}

interface PageProjection {
  readonly sources: readonly ResearchSource[];
  readonly suppliedSnapshotCount: number;
  readonly missingFirstPartyCount: number;
  readonly missingExternalCount: number;
  readonly truncatedSourceCount: number;
}

function pageSources(
  manifest: ContentShadowInputManifest,
  index: ReadonlyMap<string, RetrievedResearchSnapshot>,
): PageProjection {
  const sources: ResearchSource[] = [];
  let remainingCharacters = MAX_RESEARCH_PACK_CONTENT_CHARS;
  let suppliedSnapshotCount = 0;
  let missingFirstPartyCount = 0;
  let missingExternalCount = 0;
  let truncatedSourceCount = 0;
  const append = (bounded: BoundedPageSource): void => {
    sources.push(bounded.source);
    remainingCharacters -= bounded.consumedCharacters;
    if (bounded.bodyTruncated) truncatedSourceCount += 1;
  };

  for (const frozen of manifest.researchContext.firstPartyPageSnapshots) {
    const snapshot = index.get(`first_party_page\u0000${frozen.pageSnapshotId}`);
    const evidenceRefs = [
      `data-snapshot:${frozen.dataSnapshotId}`,
      `page-snapshot:${frozen.pageSnapshotId}`,
    ];
    if (snapshot) {
      suppliedSnapshotCount += 1;
      append(
        boundedPageSource(
          snapshot,
          {
            label: snapshot.label || frozen.url,
            authorityTier: "B",
            evidenceRefs,
          },
          remainingCharacters,
        ),
      );
      continue;
    }
    missingFirstPartyCount += 1;
    sources.push(
      emptySource({
        kind: "first_party_page",
        ref: frozen.pageSnapshotId,
        authorityTier: "B",
        label: frozen.url,
        url: frozen.url,
        availability: "partial",
        capturedAt: frozen.capturedAt,
        urlHash: frozen.urlHash,
        contentHash: frozen.contentHash,
        contentHashMethod: "sha256_canonical_extract",
        evidenceRefs,
        limitation:
          "Frozen first-party PageSnapshot identity is available, but its canonical body was not supplied to this research pack.",
      }),
    );
  }

  for (const target of manifest.researchContext.externalTargets) {
    const snapshot = index.get(`external_page\u0000${target.ref}`);
    if (snapshot) {
      suppliedSnapshotCount += 1;
      append(
        boundedPageSource(
          snapshot,
          {
            // Frozen label wins over retrieval metadata so target identity is
            // entirely determined by the hashed manifest.
            label: target.label,
            authorityTier: "B",
            evidenceRefs: [`external-target:${target.ref}`],
          },
          remainingCharacters,
        ),
      );
      continue;
    }
    missingExternalCount += 1;
    sources.push(
      emptySource({
        kind: "external_page",
        ref: target.ref,
        authorityTier: "B",
        label: target.label,
        url: target.url,
        availability: "unavailable",
        evidenceRefs: [`external-target:${target.ref}`],
        limitation:
          "No retrieved snapshot was supplied for this frozen external target.",
      }),
    );
  }

  return {
    sources,
    suppliedSnapshotCount,
    missingFirstPartyCount,
    missingExternalCount,
    truncatedSourceCount,
  };
}

function retrievalSummary(
  manifest: ContentShadowInputManifest,
  projection: PageProjection,
): ResearchRetrievalSummary {
  const sources = projection.sources;
  return {
    targetCount:
      manifest.researchContext.firstPartyPageSnapshots.length +
      manifest.researchContext.externalTargets.length,
    suppliedSnapshotCount: projection.suppliedSnapshotCount,
    availableSourceCount: sources.filter(
      (source) => source.availability === "available",
    ).length,
    partialSourceCount: sources.filter(
      (source) => source.availability === "partial",
    ).length,
    unavailableSourceCount: sources.filter(
      (source) => source.availability === "unavailable",
    ).length,
    firstPartyPageCount:
      manifest.researchContext.firstPartyPageSnapshots.length,
    externalPageCount: manifest.researchContext.externalTargets.length,
    contentSourceCount: sources.filter(
      (source) => source.contentText !== null,
    ).length,
    contentCharacterCount: sources.reduce(
      (count, source) => count + (source.contentText?.length ?? 0),
      0,
    ),
    truncatedSourceCount: projection.truncatedSourceCount,
  };
}

function plural(count: number, singular: string, pluralValue: string): string {
  return count === 1 ? singular : pluralValue;
}

function retrievalLimitations(
  manifest: ContentShadowInputManifest,
  projection: PageProjection,
  summary: ResearchRetrievalSummary,
): readonly string[] {
  const limitations: string[] = [];
  if (summary.targetCount === 0) {
    limitations.push(
      "No first-party PageSnapshot or external research target was frozen for this run.",
    );
  }
  if (manifest.researchContext.externalTargets.length === 0) {
    limitations.push(
      "No external research target was frozen in the run's actual inputs.",
    );
  }
  if (projection.missingFirstPartyCount > 0) {
    limitations.push(
      `${projection.missingFirstPartyCount} frozen first-party page ${plural(projection.missingFirstPartyCount, "snapshot body was", "snapshot bodies were")} not supplied to the pack.`,
    );
  }
  if (projection.missingExternalCount > 0) {
    limitations.push(
      `${projection.missingExternalCount} frozen external ${plural(projection.missingExternalCount, "target has", "targets have")} no retrieved snapshot.`,
    );
  }
  const suppliedPartial = projection.sources.filter(
    (source) =>
      source.availability === "partial" &&
      !source.limitation?.includes("was not supplied"),
  ).length;
  const suppliedUnavailable =
    summary.unavailableSourceCount - projection.missingExternalCount;
  if (suppliedPartial > 0) {
    limitations.push(
      `${suppliedPartial} supplied research ${plural(suppliedPartial, "snapshot is", "snapshots are")} partial; inspect its source limitation.`,
    );
  }
  if (suppliedUnavailable > 0) {
    limitations.push(
      `${suppliedUnavailable} supplied research ${plural(suppliedUnavailable, "snapshot is", "snapshots are")} unavailable; inspect its source limitation.`,
    );
  }
  if (summary.truncatedSourceCount > 0) {
    limitations.push(
      `${summary.truncatedSourceCount} research ${plural(summary.truncatedSourceCount, "source body projection was", "source body projections were")} truncated by the retrieval adapter or the pack's deterministic body-text bounds; each source retains its original audited content hash.`,
    );
  }
  return limitations;
}

function contentPolicyLimitations(
  policy: ContentShadowContentPolicy,
): readonly string[] {
  const count =
    policy.brandConstraints.length +
    policy.complianceConstraints.length +
    policy.prohibitedTerms.length +
    policy.claimRestrictions.length;
  return count === 0
    ? ["No content-policy constraint was frozen for this run."]
    : [];
}

/** Limitations derived from brief-outline projection counts. */
function briefOutlineLimitations(
  manifest: ContentShadowInputManifest,
  stats: BriefOutlineProjectionStats,
): readonly string[] {
  const limitations: string[] = [];
  if (manifest.contentBriefOutline.briefSections.length === 0) {
    limitations.push(BRIEF_OUTLINE_UNAVAILABLE_LIMITATION);
  }
  if (stats.projectedSectionCount < stats.briefSectionCount) {
    limitations.push(
      `The pinned content brief carried ${stats.briefSectionCount} distinct section headings; only the first ${stats.projectedSectionCount} (in document order) reached the draft prompt, so ${stats.briefSectionCount - stats.projectedSectionCount} committed topic(s) did not guide this draft.`,
    );
  }
  if (stats.projectedKeywordCount < stats.clusterKeywordCount) {
    limitations.push(
      `The frozen search cluster holds ${stats.clusterKeywordCount} keywords; only the first ${stats.projectedKeywordCount} (ordered by normalized keyword) were projected into the brief outline.`,
    );
  }
  if (stats.unconfirmedMappingCount > 0) {
    limitations.push(
      `${stats.unconfirmedMappingCount} of ${stats.clusterKeywordCount} frozen cluster keywords carry an unconfirmed page-mapping review state; the outline's pageAssignment therefore reflects decisions no operator has confirmed.`,
    );
  }
  return limitations;
}

/** Project one frozen manifest and already-retrieved snapshot set into a pack. */
export function buildResearchPack(
  manifest: ContentShadowInputManifest,
  briefOutlineStats: BriefOutlineProjectionStats,
  retrievedSnapshots: readonly RetrievedResearchSnapshot[],
): ResearchPack {
  const snapshotIndex = validateAndIndexSnapshots(
    manifest,
    retrievedSnapshots,
  );
  const pages = pageSources(manifest, snapshotIndex);
  const summary = retrievalSummary(manifest, pages);
  const searchFacts = manifest.researchContext.searchKeywordFacts.map(
    cloneKeywordFact,
  );
  const generativeFacts =
    manifest.researchContext.generativeKeywordFacts.map(cloneKeywordFact);
  const competitorFacts =
    manifest.researchContext.competitorFacts.map(cloneCompetitorFact);
  const sources: readonly ResearchSource[] = [
    briefSource(manifest),
    ...firstPartyIdentitySources(manifest),
    ...pages.sources.filter((source) => source.kind === "first_party_page"),
    ...keywordSources(searchFacts, "search_query"),
    ...keywordSources(generativeFacts, "generative_query"),
    ...competitorSources(competitorFacts),
    ...pages.sources.filter((source) => source.kind === "external_page"),
  ];
  if (sources.length > MAX_RESEARCH_PACK_SOURCES) {
    throw new RangeError(
      `research pack contains ${sources.length} sources (maximum ${MAX_RESEARCH_PACK_SOURCES})`,
    );
  }
  return {
    adapterVersion: manifest.flowAdapterVersion,
    projectionVersion: manifest.projectionVersion,
    outputLocale: manifest.outputLocale,
    brief: {
      artifactId: manifest.contentBriefArtifactId,
      revision: manifest.contentBriefRevision,
    },
    outline: [...CONTENT_SHADOW_OUTLINE],
    briefOutline: {
      briefSections: [...manifest.contentBriefOutline.briefSections],
      targetKeywords: [...manifest.contentBriefOutline.targetKeywords],
      pageAssignment: manifest.contentBriefOutline.pageAssignment,
    },
    searchObservation: {
      clusterKey: manifest.searchCluster.clusterKey,
      keywordEntityIds: [...manifest.searchCluster.keywordEntityIds],
      keywordFacts: searchFacts,
    },
    generativeObservation: {
      generativeQueryEntityIds: [...manifest.generativeQueryEntityIds],
      keywordFacts: generativeFacts,
    },
    competitorEntityIds: [...manifest.competitorEntityIds],
    competitorFacts,
    policy: clonePolicy(manifest.researchContext.contentPolicy),
    retrievalSummary: summary,
    sources,
    limitations: [
      ...retrievalLimitations(manifest, pages, summary),
      ...contentPolicyLimitations(manifest.researchContext.contentPolicy),
      ...briefOutlineLimitations(manifest, briefOutlineStats),
    ],
  };
}

/** The pack as a plain JSON object for the `pack` jsonb column. */
export function researchPackToJson(
  pack: ResearchPack,
): Record<string, unknown> {
  return JSON.parse(JSON.stringify(pack)) as Record<string, unknown>;
}
