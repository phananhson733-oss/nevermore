/** A supplied snapshot did not resolve exactly to an authorized frozen target. */
export class ResearchSnapshotIntegrityError extends Error {
  readonly code = "CONTENT_SHADOW_RESEARCH_SNAPSHOT_INTEGRITY";

  constructor(detail: string) {
    super(`research snapshot integrity check failed: ${detail}`);
    this.name = "ResearchSnapshotIntegrityError";
  }
}

function snapshotKey(snapshot: RetrievedResearchSnapshot): string {
  return `${snapshot.kind}\u0000${snapshot.ref}`;
}

function assertSnapshotCoherence(snapshot: RetrievedResearchSnapshot): void {
  if (typeof snapshot.contentTruncated !== "boolean") {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} contentTruncated must be boolean`,
    );
  }
  if (typeof snapshot.excerptTruncated !== "boolean") {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} excerptTruncated must be boolean`,
    );
  }
  if (
    snapshot.limitation !== null &&
    (snapshot.limitation.trim().length === 0 ||
      snapshot.limitation !== snapshot.limitation.trim() ||
      snapshot.limitation.length > MAX_RESEARCH_SOURCE_LIMITATION_CHARS)
  ) {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} limitation must be non-blank, unpadded and at most ${MAX_RESEARCH_SOURCE_LIMITATION_CHARS} characters`,
    );
  }
  if (
    snapshot.availability === "unavailable" &&
    snapshot.contentText !== null
  ) {
    throw new ResearchSnapshotIntegrityError(
      `unavailable ${snapshot.kind} ${snapshot.ref} supplied a content body`,
    );
  }
  if (
    (snapshot.contentHash === null) !==
    (snapshot.contentHashMethod === null)
  ) {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} must pair contentHash with contentHashMethod`,
    );
  }
  if (snapshot.contentText !== null && snapshot.contentHash === null) {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} supplied content without an auditable content hash`,
    );
  }
  if (
    snapshot.contentText !== null &&
    (snapshot.url === null ||
      snapshot.capturedAt === null ||
      snapshot.urlHash === null)
  ) {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} supplied content without terminal URL, capture time and URL hash`,
    );
  }
  if (
    snapshot.contentTruncated &&
    (snapshot.contentText === null ||
      snapshot.contentHash === null ||
      snapshot.contentHashMethod === null)
  ) {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} set contentTruncated without an auditable body and content hash`,
    );
  }
  if (
    snapshot.contentTruncated &&
    snapshot.availability !== "partial"
  ) {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} set contentTruncated but adapter availability was not partial`,
    );
  }
  if (snapshot.excerpt !== null && snapshot.contentText === null) {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} supplied an excerpt without a retained body`,
    );
  }
  if (
    snapshot.excerptTruncated &&
    (snapshot.excerpt === null || snapshot.contentText === null)
  ) {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} set excerptTruncated without an excerpt and retained body`,
    );
  }
  if (
    snapshot.excerptTruncated &&
    snapshot.excerpt !== null &&
    snapshot.contentText !== null &&
    [...snapshot.excerpt].length >= [...snapshot.contentText].length
  ) {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} set excerptTruncated but the excerpt is not shorter than the retained body`,
    );
  }
  if (snapshot.urlHash !== null && snapshot.url === null) {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} supplied a URL hash without a terminal URL`,
    );
  }
  const metrics = snapshot.metrics;
  if (metrics === null) return;
  if (
    metrics.status !== null &&
    (!Number.isSafeInteger(metrics.status) ||
      metrics.status < 100 ||
      metrics.status > 599)
  ) {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} metrics.status must be an HTTP status or null`,
    );
  }
  for (const [label, value] of [
    ["bodyBytes", metrics.bodyBytes],
    ["wordCount", metrics.wordCount],
    ["responseMs", metrics.responseMs],
  ] as const) {
    if (
      value !== null &&
      (!Number.isSafeInteger(value) || value < 0)
    ) {
      throw new ResearchSnapshotIntegrityError(
        `${snapshot.kind} ${snapshot.ref} metrics.${label} must be a non-negative safe integer or null`,
      );
    }
  }
  if (metrics.redirectChain.length > MAX_RESEARCH_SOURCE_REDIRECTS) {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} redirect chain exceeds ${MAX_RESEARCH_SOURCE_REDIRECTS} hops`,
    );
  }
  for (const redirect of metrics.redirectChain) {
    try {
      const parsed = new URL(redirect.trim());
      if (
        (parsed.protocol !== "https:" && parsed.protocol !== "http:") ||
        parsed.hostname.length === 0
      ) {
        throw new Error("not http");
      }
    } catch {
      throw new ResearchSnapshotIntegrityError(
        `${snapshot.kind} ${snapshot.ref} redirect entries must be absolute http(s) URLs`,
      );
    }
  }
}

function canonicalSnapshot(
  snapshot: RetrievedResearchSnapshot,
): RetrievedResearchSnapshot {
  assertSnapshotCoherence(snapshot);
  const evidenceRefs = sortedUnique(snapshot.evidenceRefs);
  if (evidenceRefs.length > MAX_RESEARCH_SOURCE_EVIDENCE_REFS) {
    throw new ResearchSnapshotIntegrityError(
      `${snapshot.kind} ${snapshot.ref} has too many evidence references`,
    );
  }
  const normalized: RetrievedResearchSnapshot = {
    ref: snapshot.ref.trim(),
    kind: snapshot.kind,
    label: truncate(
      snapshot.label.trim(),
      MAX_RESEARCH_SOURCE_LABEL_CHARS,
    ),
    requestedUrl: snapshot.requestedUrl.trim(),
    url: nullableTrimmed(snapshot.url),
    availability: snapshot.availability,
    capturedAt: nullableTrimmed(snapshot.capturedAt),
    urlHash: nullableTrimmed(snapshot.urlHash),
    contentHash: nullableTrimmed(snapshot.contentHash),
    contentHashMethod: snapshot.contentHashMethod,
    // Preserve body bytes exactly here. Bounding happens only after snapshot
    // integrity is established, and never changes the supplied content hash.
    contentText: snapshot.contentText,
    contentTruncated: snapshot.contentTruncated,
    excerpt: snapshot.excerpt,
    excerptTruncated: snapshot.excerptTruncated,
    metrics: cloneMetrics(snapshot.metrics),
    evidenceRefs,
    limitation: snapshot.limitation,
  };
  assertSnapshotCoherence(normalized);
  return normalized;
}

function canonicalSnapshots(
  snapshots: readonly RetrievedResearchSnapshot[],
): readonly RetrievedResearchSnapshot[] {
  const normalized = snapshots.map(canonicalSnapshot);
  normalized.sort((left, right) =>
    compareText(snapshotKey(left), snapshotKey(right)),
  );
  const result: RetrievedResearchSnapshot[] = [];
  for (const snapshot of normalized) {
    const previous = result.at(-1);
    if (!previous || snapshotKey(previous) !== snapshotKey(snapshot)) {
      result.push(snapshot);
      continue;
    }
    if (JSON.stringify(previous) !== JSON.stringify(snapshot)) {
      throw new ResearchSnapshotIntegrityError(
        `conflicting values were supplied for ${snapshot.kind} ${snapshot.ref}`,
      );
    }
  }
  return result;
}

function assertEqual(
  actual: unknown,
  expected: unknown,
  detail: string,
): void {
  if (actual !== expected) {
    throw new ResearchSnapshotIntegrityError(detail);
  }
}

function assertFirstPartySnapshot(
  snapshot: RetrievedResearchSnapshot,
  frozen: ContentShadowFirstPartyPageSnapshotIdentity,
): void {
  if (
    snapshot.availability !== "available" ||
    snapshot.contentText === null
  ) {
    throw new ResearchSnapshotIntegrityError(
      `first-party PageSnapshot ${frozen.pageSnapshotId} must be supplied as an available body or omitted entirely`,
    );
  }
  assertEqual(
    snapshot.requestedUrl,
    frozen.url,
    `first-party PageSnapshot ${frozen.pageSnapshotId} requested URL drifted`,
  );
  assertEqual(
    snapshot.url,
    frozen.url,
    `first-party PageSnapshot ${frozen.pageSnapshotId} URL drifted`,
  );
  assertEqual(
    snapshot.capturedAt,
    frozen.capturedAt,
    `first-party PageSnapshot ${frozen.pageSnapshotId} capturedAt drifted`,
  );
  assertEqual(
    snapshot.urlHash,
    frozen.urlHash,
    `first-party PageSnapshot ${frozen.pageSnapshotId} URL hash drifted`,
  );
  assertEqual(
    snapshot.contentHash,
    frozen.contentHash,
    `first-party PageSnapshot ${frozen.pageSnapshotId} content hash drifted`,
  );
  assertEqual(
    snapshot.contentHashMethod,
    "sha256_canonical_extract",
    `first-party PageSnapshot ${frozen.pageSnapshotId} uses the wrong content-hash method`,
  );
}

function assertExternalSnapshot(
  snapshot: RetrievedResearchSnapshot,
  target: ContentShadowExternalResearchTarget,
): void {
  assertEqual(
    snapshot.requestedUrl,
    target.url,
    `external target ${target.ref} requested URL drifted`,
  );
  if (snapshot.availability === "available") {
    if (
      snapshot.url === null ||
      snapshot.capturedAt === null ||
      snapshot.urlHash === null ||
      snapshot.contentHash === null ||
      snapshot.contentHashMethod !== "sha256_normalized_text"
    ) {
      throw new ResearchSnapshotIntegrityError(
        `available external target ${target.ref} lacks terminal URL, capture time or reproducible hashes`,
      );
    }
  }
  if (
    snapshot.contentHash !== null &&
    snapshot.contentHashMethod !== "sha256_normalized_text"
  ) {
    throw new ResearchSnapshotIntegrityError(
      `external target ${target.ref} uses the wrong content-hash method`,
    );
  }
}

function validateAndIndexSnapshots(
  manifest: ContentShadowInputManifest,
  retrievedSnapshots: readonly RetrievedResearchSnapshot[],
): ReadonlyMap<string, RetrievedResearchSnapshot> {
  const firstParty = new Map(
    manifest.researchContext.firstPartyPageSnapshots.map((snapshot) => [
      snapshot.pageSnapshotId,
      snapshot,
    ]),
  );
  const external = new Map(
    manifest.researchContext.externalTargets.map((target) => [
      target.ref,
      target,
    ]),
  );
  const index = new Map<string, RetrievedResearchSnapshot>();
  for (const snapshot of canonicalSnapshots(retrievedSnapshots)) {
    if (snapshot.kind === "first_party_page") {
      const frozen = firstParty.get(snapshot.ref);
      if (!frozen) {
        throw new ResearchSnapshotIntegrityError(
          `first-party snapshot ${snapshot.ref} is not present in the frozen research context`,
        );
      }
      assertFirstPartySnapshot(snapshot, frozen);
    } else {
      const target = external.get(snapshot.ref);
      if (!target) {
        throw new ResearchSnapshotIntegrityError(
          `external target ${snapshot.ref} is not present in the frozen research context`,
        );
      }
      assertExternalSnapshot(snapshot, target);
    }
    index.set(snapshotKey(snapshot), snapshot);
  }
  return index;
}

function emptySource(
  fields: Pick<
    ResearchSource,
    "kind" | "ref" | "authorityTier" | "label" | "url" | "availability"
  > & {
    readonly limitation: string | null;
    readonly capturedAt?: string | null;
    readonly urlHash?: string | null;
    readonly contentHash?: string | null;
    readonly contentHashMethod?: ResearchSource["contentHashMethod"];
    readonly evidenceRefs?: readonly string[];
  },
): ResearchSource {
  return {
    kind: fields.kind,
    ref: fields.ref,
    authorityTier: fields.authorityTier,
    label: fields.label,
    url: fields.url,
    availability: fields.availability,
    capturedAt: fields.capturedAt ?? null,
    urlHash: fields.urlHash ?? null,
    contentHash: fields.contentHash ?? null,
    contentHashMethod: fields.contentHashMethod ?? null,
    contentText: null,
    contentTruncated: false,
    excerpt: null,
    excerptTruncated: false,
    metrics: null,
    evidenceRefs: [...(fields.evidenceRefs ?? [])],
    limitation: fields.limitation,
  };
}

