/**
 * Deterministic research-pack assembly.
 *
 * Retrieval is intentionally outside this module. The worker freezes targets,
 * an outer adapter obtains immutable snapshot values, and this pure function
 * verifies those values against the manifest before producing a bounded pack.
 * It reads no clock, environment, filesystem, database or network.
 */

