// @input  -- Server-authenticated POST {code, destination_url} from the link tool
// @output -- 201 created, 200 reused, or explicit validation/storage failures
// @pos    -- Marketing-only short-link registration; no product app writes
import { timingSafeEqual } from "node:crypto";
import { NextResponse } from "next/server";
import { registerShortLink } from "../../../../lib/link-attribution/short-links";

export const dynamic = "force-dynamic";
const ORIGINS = new Set(["null", "https://gengrowth.ai", "https://www.gengrowth.ai"]);

function reply(request: Request, body: unknown, status: number) {
  const origin = request.headers.get("origin");
  return NextResponse.json(body, { status, headers: {
    "Cache-Control": "no-store", Vary: "Origin",
    ...(origin && ORIGINS.has(origin) ? { "Access-Control-Allow-Origin": origin } : {}),
    "Access-Control-Allow-Methods": "POST, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type, x-link-attribution-tool-key",
  } });
}

export function OPTIONS(request: Request) {
  const origin = request.headers.get("origin");
  const response = reply(request, {}, origin && !ORIGINS.has(origin) ? 403 : 200);
  return new Response(null, { status: response.status === 200 ? 204 : 403, headers: response.headers });
}

export async function POST(request: Request) {
  const origin = request.headers.get("origin");
  if (origin && !ORIGINS.has(origin)) return reply(request, { error: { code: "FORBIDDEN_ORIGIN", message: "Origin is not allowed." } }, 403);
  const expected = process.env.GENGROWTH_LINK_TOOL_KEY;
  if (process.env.MARKETING_SHORT_LINKS_ENABLED !== "true" || !expected) {
    return reply(request, { error: { code: "STORAGE_UNCONFIGURED", message: "Short-link registration is not enabled." } }, 503);
  }
  const supplied = request.headers.get("x-link-attribution-tool-key") || "";
  const a = Buffer.from(supplied), b = Buffer.from(expected);
  if (a.length !== b.length || !timingSafeEqual(a, b)) return reply(request, { error: { code: "FORBIDDEN", message: "Registration key is required." } }, 403);
  if (!request.headers.get("content-type")?.toLowerCase().startsWith("application/json")) {
    return reply(request, { error: { code: "INVALID_JSON", message: "Content-Type must be application/json." } }, 415);
  }
  let body: { code?: unknown; destination_url?: unknown };
  try {
    if (Number(request.headers.get("content-length")) > 16384) return reply(request, { error: { code: "PAYLOAD_TOO_LARGE", message: "Request is too large." } }, 413);
    const text = await request.text();
    if (Buffer.byteLength(text) > 16384) return reply(request, { error: { code: "PAYLOAD_TOO_LARGE", message: "Request is too large." } }, 413);
    const parsed: unknown = JSON.parse(text);
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) throw new Error("Invalid object");
    body = parsed;
  } catch {
    return reply(request, { error: { code: "INVALID_JSON", message: "Request body must be a JSON object." } }, 400);
  }
  if (typeof body.code !== "string" || !/^q1[a-z0-9]{12}$/.test(body.code)) {
    return reply(request, { error: { code: "INVALID_CODE", message: "Use the stable short code generated by the link tool." } }, 400);
  }
  try {
    const result = await registerShortLink(body.code, body.destination_url);
    if (!result.ok) return reply(request, { error: { code: result.code, message: result.message } }, result.status);
    return reply(request, { data: { code: result.code, destination_url: result.destinationUrl, reused: result.reused, short_url: `https://gengrowth.ai/${result.code}` } }, result.reused ? 200 : 201);
  } catch {
    return reply(request, { error: { code: "STORAGE_UNCONFIGURED", message: "Short-link storage is unavailable. Please retry." } }, 503);
  }
}
